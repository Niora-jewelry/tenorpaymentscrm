const subtabRows: string[] = [];
for (const t of ALL_TABS) {
  (t.subtabs ?? []).forEach((s, i) => {
    subtabRows.push(
      `  (${sqlStr(t.id)}, ${sqlStr(s.id)}, ${sqlStr(s.label)}, ${sqlStrOrNull(s.description)}, ${i * 10}, ${sqlBool(s.comingSoon)})`,
    );
  });
}
if (subtabRows.length) {
  push('-- ── Subtabs ──────────────────────────────────────────────────────────────');
  push('insert into subtabs (tab_id, key, label, description, position, coming_soon)');
  push('select t.id, v.key, v.label, v.description, v.position, v.coming_soon');
  push('from (values');
  push(subtabRows.join(',\n'));
  push(') as v(tab_key, key, label, description, position, coming_soon)');
  push('join tabs t on t.key = v.tab_key;');
  push('');
}

