push('insert into pipeline_steps (pipeline_id, label, swatch, position)');
push('select pl.id, v.label, v.swatch::swatch, v.position');
push('from (values');
push(stepRows.join(',\n'));
push(') as v(pipeline_label, module_slug, label, swatch, position)');
push('join modules mo on mo.slug = v.module_slug');
push('join pipelines pl on pl.module_id = mo.id and pl.label = v.pipeline_label;');
push('');

/* -------------------------------------------------------------------------- */
/* Statement periods — July 2024 through December 2032, 102 rows              */
/* -------------------------------------------------------------------------- */

const periodRows: string[] = [];
for (let year = 2024; year <= 2032; year++) {
  const startMonth = year === 2024 ? 7 : 1;
  const endMonth = year === 2032 ? 12 : 12;
  for (let month = startMonth; month <= endMonth; month++) {
    periodRows.push(`  (${year}, ${month})`);
  }
}
push(`-- ── Statement periods — Jul 2024 through Dec 2032, ${periodRows.length} rows ──────────`);
push('insert into statement_periods (year, month) values');
push(periodRows.join(',\n') + ';');
push('');

