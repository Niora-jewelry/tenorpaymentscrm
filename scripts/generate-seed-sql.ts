/**
 * Generates supabase/migrations/20260819001000_module2_seed.sql directly from
 * src/proto/fields.ts and src/proto/modules.ts — the prototype's own data,
 * already checked against CRM-19aug.xlsx row by row (see the Stage 0 audit).
 * This is the concrete mechanism for "zero drift from the client's sheet":
 * nothing here is retyped by hand, so a field cannot silently diverge between
 * what the prototype renders and what the real database seeds.
 *
 * All foreign keys are resolved by KEY, not by pre-assigned UUID: every
 * INSERT either carries a `key`/`slug` directly (modules, tabs, subtabs,
 * fields) or joins back to one via a subquery (module_tab_order, fields.tab_id,
 * field_choices, …). That is what makes this script independent of Postgres's
 * gen_random_uuid() output — it never needs to know an id in advance.
 *
 * Usage: npx tsx scripts/generate-seed-sql.ts
 */
import { writeFileSync } from 'node:fs';
import { FIELDS } from '../src/proto/fields';
import { ALL_TABS, MODULES, PIPELINES } from '../src/proto/modules';
import type { Field } from '../src/proto/schema';

/* -------------------------------------------------------------------------- */
/* SQL literal helpers                                                        */
/* -------------------------------------------------------------------------- */

function sqlStr(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}
function sqlStrOrNull(s: string | undefined | null): string {
  return s == null ? 'null' : sqlStr(s);
}
function sqlBool(b: boolean | undefined): string {
  return b ? 'true' : 'false';
}
function sqlIntOrNull(n: number | undefined | null): string {
  return n == null ? 'null' : String(n);
}
function sqlJsonbOrNull(v: unknown): string {
  return v == null ? 'null' : `${sqlStr(JSON.stringify(v))}::jsonb`;
}
function sqlIntArrayOrNull(arr: number[] | undefined): string {
  return arr == null ? 'null' : `'{${arr.join(',')}}'::int[]`;
}
/** Stable choice key — SCHEMA-DECISIONS §3: JSONB stores this, never the label. */
function slugify(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

