const columnRows: string[] = [];
const headerRows: string[] = [];
for (const f of FIELDS) {
  if (f.repeatGroup) continue; // repeat groups are never dashboard columns or header fields
  f.columnIn.forEach((slug) => {
    columnRows.push(`  (${sqlStr(slug)}, ${sqlStr(f.id)}, ${f.columnOrder ?? 999})`);
  });
  (f.headerIn ?? []).forEach((slug) => {
    headerRows.push(`  (${sqlStr(slug)}, ${sqlStr(f.id)}, 0)`);
  });
}

if (columnRows.length) {
  push('-- ── Dashboard columns — properties (a)(b) ───────────────────────────────');
  push('insert into module_columns (module_id, field_id, position)');
  push('select mo.id, fl.id, v.position');
  push('from (values');
  push(columnRows.join(',\n'));
  push(') as v(module_slug, field_key, position)');
  push('join modules mo on mo.slug = v.module_slug');
  push('join fields fl on fl.key = v.field_key;');
  push('');
}

if (headerRows.length) {
  push('-- ── Header-strip membership — property (e) ──────────────────────────────');
  push('insert into module_header_fields (module_id, field_id, position)');
  push('select mo.id, fl.id, v.position');
  push('from (values');
  push(headerRows.join(',\n'));
  push(') as v(module_slug, field_key, position)');
  push('join modules mo on mo.slug = v.module_slug');
  push('join fields fl on fl.key = v.field_key;');
  push('');
}

const choiceRows: string[] = [];
for (const f of FIELDS) {
  if (f.repeatGroup) continue;
  (f.choices ?? []).forEach((c, i) => {
    choiceRows.push(
      `  (${sqlStr(f.id)}, null, ${sqlStr(slugify(c.value))}, ${sqlStr(c.value)}, ${sqlStrOrNull(c.swatch)}, ${i * 10})`,
    );
  });
  Object.entries(f.choicesByModule ?? {}).forEach(([slug, choices]) => {
    (choices ?? []).forEach((c, i) => {
      choiceRows.push(
        `  (${sqlStr(f.id)}, ${sqlStr(slug)}, ${sqlStr(slugify(c.value))}, ${sqlStr(c.value)}, ${sqlStrOrNull(c.swatch)}, ${i * 10})`,
      );
    });
  });
}

if (choiceRows.length) {
  push('-- ── Choices — property (f), stored by stable key (SCHEMA-DECISIONS §3) ──');
  push('insert into field_choices (field_id, module_id, key, value, swatch, position)');
  push('select fl.id, mo.id, v.choice_key, v.value, v.swatch::swatch, v.position');
  push('from (values');
  push(choiceRows.join(',\n'));
  push(') as v(field_key, module_slug, choice_key, value, swatch, position)');
  push('join fields fl on fl.key = v.field_key');
  push('left join modules mo on mo.slug = v.module_slug;');
  push('');
}

