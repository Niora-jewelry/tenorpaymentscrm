/* Per-module tab/subtab order                                                 */
/* -------------------------------------------------------------------------- */

const tabOrderRows: string[] = [];
const subtabOrderRows: string[] = [];
for (const m of MODULES) {
  const orderedTabIds = [...m.customTabOrder, ...m.systemTabOrder];
  orderedTabIds.forEach((tabId, i) => {
    tabOrderRows.push(`  (${sqlStr(m.slug)}, ${sqlStr(tabId)}, ${i * 10})`);
  });
  for (const tabId of orderedTabIds) {
    const tab = ALL_TABS.find((t) => t.id === tabId);
    if (!tab || !tab.subtabs?.length) continue;
    const order = m.subtabOrder?.[tabId] ?? tab.subtabs.map((s) => s.id);
    order.forEach((subtabId, i) => {
      subtabOrderRows.push(`  (${sqlStr(m.slug)}, ${sqlStr(tabId)}, ${sqlStr(subtabId)}, ${i * 10})`);
    });
  }
}

push('-- ── Per-module tab order — property (c) ─────────────────────────────────');
push('insert into module_tab_order (module_id, tab_id, position)');
push('select mo.id, t.id, v.position');
push('from (values');
push(tabOrderRows.join(',\n'));
push(') as v(module_slug, tab_key, position)');
push('join modules mo on mo.slug = v.module_slug');
push('join tabs t on t.key = v.tab_key;');
push('');

push('-- ── Per-module subtab order — property (d) ───────────────────────────────');
push('insert into module_subtab_order (module_id, subtab_id, position)');
push('select mo.id, s.id, v.position');
push('from (values');
push(subtabOrderRows.join(',\n'));
push(') as v(module_slug, tab_key, subtab_key, position)');
push('join modules mo on mo.slug = v.module_slug');
push('join tabs t on t.key = v.tab_key');
push('join subtabs s on s.tab_id = t.id and s.key = v.subtab_key;');
push('');

/* -------------------------------------------------------------------------- */
/* Fields — repeat groups collapsed into ONE 'repeat_group' row each          */
/* (SCHEMA-DECISIONS §1), everything else emitted 1:1 from FIELDS.            */
/* -------------------------------------------------------------------------- */

function splitTab(tab: string): { tabKey: string; subtabKey: string | null } {
  const [tabKey, subtabKey] = tab.split('/');
  return { tabKey: tabKey!, subtabKey: subtabKey ?? null };
}

function memberKeyOf(id: string, groupKey: string): string {
  let m = id.match(new RegExp(`^${groupKey}_1_(.+)$`));
  if (m) return m[1]!;
  m = id.match(new RegExp(`^${groupKey}_(.+)_1$`));
  if (m) return m[1]!;
  throw new Error(`generate-seed-sql: can't derive member key for "${id}" (group "${groupKey}")`);
}

function memberLabelOf(label: string, groupKey: string): string {
  let s = label.replace(/\b1\b/, '').replace(/\s+/g, ' ').trim();
  const prefix = groupKey.charAt(0).toUpperCase() + groupKey.slice(1);
  if (s.toLowerCase().startsWith(prefix.toLowerCase() + ' ')) s = s.slice(prefix.length + 1);
  return s.charAt(0).toUpperCase() + s.slice(1);
}

type FieldRow = {
  key: string;
  label: string;
  type: string;
  tabKey: string;
  subtabKey: string | null;
  position: number;
  hint?: string;
  notesEnabled: boolean;
  syncEnabled: boolean;
  isSystem: boolean;
  readOnly: boolean;
  required: boolean;
  sensitive: boolean;
  wide: boolean;
  placeholder: boolean;
  width?: number;
  digits?: number[];
  repeatMax?: number;
  repeatSchema?: unknown;
  repeatGroupKey?: string;
  gridColumns?: unknown;
};

// A repeat group's key ('owner', 'contact', …) is shared by every member
// field, but the group itself is placed per TAB/SUBTAB — the Amendment's
// "a field lives in exactly one tab, always" applies to the collapsed
// repeat_group row exactly as it does to an ordinary field. 'owner' actually
// spans TWO locations (Private holds just the SSN member; Ownership holds
// the other six) — the prototype's shared instanceCount() treats both as one
// logical entity, but `fields.key` is unique, so a group that spans more
// than one location gets a location-qualified key ('owner_private',
// 'owner_ownership') while a single-location group keeps its bare key
// ('contacts', 'affiliates'). Stage 2's data layer is where the two arrays'
// lengths get kept in sync when "Add owner" is clicked from either subtab —
// a follow-up for that stage, not a migrations-stage concern.
const groupLocations = new Map<string, Set<string>>();
for (const f of FIELDS) {
  if (!f.repeatGroup) continue;
  const { tabKey, subtabKey } = splitTab(f.tab);
  const set = groupLocations.get(f.repeatGroup.key) ?? new Set<string>();
  set.add(`${tabKey}/${subtabKey ?? ''}`);
  groupLocations.set(f.repeatGroup.key, set);
}

const fieldRows: FieldRow[] = [];
const emittedRepeatGroups = new Set<string>(); // `${tabKey}/${subtabKey}::${groupKey}`

FIELDS.forEach((f: Field, i) => {
  const { tabKey, subtabKey } = splitTab(f.tab);

  if (f.repeatGroup) {
    const groupId = `${tabKey}/${subtabKey ?? ''}::${f.repeatGroup.key}`;
    if (emittedRepeatGroups.has(groupId)) return; // member already merged into the group row
    emittedRepeatGroups.add(groupId);

    const members = FIELDS.filter((mf) => {
      if (!mf.repeatGroup || mf.repeatGroup.key !== f.repeatGroup!.key) return false;
      const mt = splitTab(mf.tab);
      return mt.tabKey === tabKey && mt.subtabKey === subtabKey;
    });

    const schema = members.map((mf) => ({
      key: memberKeyOf(mf.id, f.repeatGroup!.key),
      label: memberLabelOf(mf.label, f.repeatGroup!.key),
      type: mf.type,
      sensitive: mf.sensitive ?? false,
      sync: mf.sync ?? false,
      digits: mf.digits,
      hint: mf.hint,
      width: mf.width,
    }));

    const groupKey = f.repeatGroup.key;
    const multiLocation = (groupLocations.get(groupKey)?.size ?? 0) > 1;
    const fieldKey = multiLocation ? `${groupKey}_${subtabKey ?? tabKey}` : groupKey;
    fieldRows.push({
      key: fieldKey,
      label: groupKey.charAt(0).toUpperCase() + groupKey.slice(1) + 's',
      type: 'repeat_group',
      tabKey,
      subtabKey,
      position: i * 10,
      notesEnabled: false,
      syncEnabled: false,
      isSystem: false,
      readOnly: false,
      required: false,
      sensitive: false,
      wide: true,
      placeholder: false,
      repeatMax: f.repeatGroup.max,
      repeatSchema: schema,
      repeatGroupKey: groupKey,
    });
    return;
  }

  fieldRows.push({
    key: f.id,
    label: f.label,
    type: f.type,
    tabKey,
    subtabKey,
    position: i * 10,
    hint: f.hint,
    notesEnabled: f.notes ?? false,
    syncEnabled: f.sync ?? false,
    isSystem: f.system ?? false,
    readOnly: f.readOnly ?? false,
    required: f.required ?? false,
    sensitive: f.sensitive ?? false,
    wide: f.wide ?? false,
    placeholder: f.placeholder ?? false,
    width: f.width,
    digits: f.digits,
    gridColumns: f.columns,
  });
});

push(`-- ── Fields (${fieldRows.length} rows: ${FIELDS.length} prototype entries, repeat`);
push(`--    groups collapsed into one 'repeat_group' row each per SCHEMA-DECISIONS §1) ──`);
push('insert into fields (');
push('  key, label, type, tab_id, subtab_id, position, hint, notes_enabled, sync_enabled,');
push('  is_system, read_only, required, sensitive, wide, placeholder, width, digits,');
push('  repeat_max, repeat_schema, repeat_group_key, grid_columns');
push(')');
push('select');
push('  v.key, v.label, v.type::field_type, t.id, s.id, v.position, v.hint, v.notes_enabled,');
push('  v.sync_enabled, v.is_system, v.read_only, v.required, v.sensitive, v.wide,');
push('  v.placeholder, v.width, v.digits, v.repeat_max, v.repeat_schema, v.repeat_group_key, v.grid_columns');
push('from (values');
push(
  fieldRows
    .map(
      (r) =>
        `  (${sqlStr(r.key)}, ${sqlStr(r.label)}, ${sqlStr(r.type)}, ${sqlStr(r.tabKey)}, ${sqlStrOrNull(r.subtabKey)}, ` +
        `${r.position}, ${sqlStrOrNull(r.hint)}, ${sqlBool(r.notesEnabled)}, ${sqlBool(r.syncEnabled)}, ` +
        `${sqlBool(r.isSystem)}, ${sqlBool(r.readOnly)}, ${sqlBool(r.required)}, ${sqlBool(r.sensitive)}, ` +
        `${sqlBool(r.wide)}, ${sqlBool(r.placeholder)}, ${sqlIntOrNull(r.width)}, ${sqlIntArrayOrNull(r.digits)}, ` +
        `${sqlIntOrNull(r.repeatMax)}, ${sqlJsonbOrNull(r.repeatSchema)}, ${sqlStrOrNull(r.repeatGroupKey)}, ${sqlJsonbOrNull(r.gridColumns)})`,
    )
    .join(',\n'),
);
push(
  ') as v(key, label, type, tab_key, subtab_key, position, hint, notes_enabled, sync_enabled,',
);
push('       is_system, read_only, required, sensitive, wide, placeholder, width, digits,');
push('       repeat_max, repeat_schema, repeat_group_key, grid_columns)');
push('join tabs t on t.key = v.tab_key');
push('left join subtabs s on s.tab_id = t.id and s.key = v.subtab_key;');
push('');

